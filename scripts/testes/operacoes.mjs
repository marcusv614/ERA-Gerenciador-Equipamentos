import assert from 'node:assert/strict';
import { Cliente, configuracaoTeste, hoje } from './cliente.mjs';
const config = configuracaoTeste(), clientes = {};
for (const conta of config.contas) clientes[conta.login.slice(5)] = await new Cliente(config).entrar(conta.login,conta.senha);
const { admin,gerente,financeiro,estoque,rh,tecnico1,tecnico2,tst } = clientes;
const origem = config.obras[0], destino = config.obras[2], f = config.funcionarios.tecnico1;
const cadastrar = (modelo,serie,quantidade=1,obra) => admin.req('POST','/equipamentos',{tipo:modelo.includes('Fluke')?'Fluke':'Ferramentas',modelo,serie,quantidade,controleQuantidade:quantidade===1?'INDIVIDUAL':'LOTE',obraId:obra?.id,tecnico:obra?f.nome:undefined,status:obra?'Em campo':'Em estoque',data:hoje(),auditavel:true},201);
const consultar = async id => (await admin.req('GET','/equipamentos')).find(e=>e.id===id);
let e = await cadastrar('Lote manutenção','OPS-MAN',3,origem);
await tecnico1.req('POST',`/equipamentos/${e.id}/manutencoes`,{quantidade:1,motivo:'Defeito'},403);
await gerente.req('POST',`/equipamentos/${e.id}/manutencoes`,{quantidade:0,motivo:''},400);
e = await gerente.req('POST',`/equipamentos/${e.id}/manutencoes`,{quantidade:1,motivo:'Uma unidade com defeito'});
const m = e.manutencoes[0];
assert.equal(e.quantidadeDisponivel,2);assert.equal(e.obraId,origem.id);
await estoque.req('POST',`/equipamentos/${e.id}/manutencoes`,{quantidade:3,motivo:'Excede saldo livre'},409);
e = await estoque.req('POST',`/equipamentos/${e.id}/manutencoes/${m.id}/conclusao`,{observacao:'Conferida e liberada'});
assert.equal(e.quantidadeDisponivel,3);
await estoque.req('POST',`/equipamentos/${e.id}/manutencoes/${m.id}/conclusao`,{observacao:'Não pode concluir novamente'},409);

let fluke = await cadastrar('Fluke DSX-5000','OPS-FLUKE',1,origem);
await rh.req('POST',`/equipamentos/${fluke.id}/calibracoes`,{},403);
fluke = await gerente.req('POST',`/equipamentos/${fluke.id}/calibracoes`,{laboratorio:'Laboratório fictício',observacao:'Calibração periódica'});
const c = fluke.calibracoes[0], rota = `/equipamentos/${fluke.id}/calibracoes/${c.id}`;
assert.equal(fluke.quantidadeDisponivel,0);assert.equal(fluke.obraId,origem.id);
await estoque.req('POST',`${rota}/envio`,{laboratorio:'Laboratório fictício',dataEnvio:hoje()},409);
await gerente.req('POST',`${rota}/retirada`,{dataRetirada:hoje()},403);
await estoque.req('POST',`${rota}/retirada`,{dataRetirada:hoje()});
fluke = await estoque.req('POST',`${rota}/envio`,{laboratorio:'Laboratório fictício',dataEnvio:hoje()});
assert.equal(fluke.status,'Em calibração');assert.equal(fluke.obraId,null);
await gerente.req('POST',`${rota}/cancelamento`,{motivo:'Não pode desaparecer do laboratório'},409);
const validade = new Date();validade.setUTCFullYear(validade.getUTCFullYear()+1);
fluke = await estoque.req('POST',`${rota}/retorno`,{dataRetorno:hoje(),dataCalibracao:hoje(),validade:validade.toISOString().slice(0,10),certificado:'CERT-OPS-001',observacao:'Aprovado pelo laboratório'});
assert.equal(fluke.status,'Em estoque');assert.equal(fluke.quantidadeDisponivel,1);
assert.equal(fluke.calibracoes[0].localOrigem,origem.nome);assert.equal(fluke.calibracoes[0].certificado,'CERT-OPS-001');
assert.ok(fluke.calibracoes[0].eventos.some(ev=>ev.autorLogin==='demo.estoque'));
console.log('Manutenção e calibração reais: bloqueio parcial, sequência física, autoria, origem e certificado preservados.');

const auditorias = `/funcionarios/${f.id}/auditorias`;
const ficha = await gerente.req('POST',auditorias,{equipamentoIds:[e.id]},201);
const registro = {versao:ficha.versao,dataVistoria:hoje(),fiscal:'Fiscal fictício',concluir:false,observacoes:'Conferência de teste',itens:ficha.itens.map(i=>({equipamentoId:i.equipamentoId,bom:3,avaria:0,quebrado:0}))};
const salva = await gerente.req('PATCH',`${auditorias}/${ficha.id}`,registro);
await gerente.req('PATCH',`${auditorias}/${ficha.id}`,registro,409);
const concluida = await gerente.req('PATCH',`${auditorias}/${ficha.id}`,{...registro,versao:salva.versao,concluir:true});
assert.ok(concluida.concluidaEm);assert.equal(concluida.itens[0].bom,3);
await rh.req('GET',`${auditorias}/${ficha.id}`,undefined,[403,404]);
await tecnico1.req('GET',`${auditorias}/${ficha.id}`,undefined,403);
console.log('Vistorias: persistência, versão desatualizada bloqueada e isolamento de acesso.');

const unico = await cadastrar('Unidade concorrente','OPS-RACE');
const criar = () => gerente.req('POST','/atividades',{tecnico:config.funcionarios.tecnico2.nome,obraDestinoId:destino.id,dataSolicitacao:hoje(),materiais:[{nome:unico.modelo,catalogoChave:unico.catalogoChave,quantidade:1}]},201);
const p1 = await criar(),p2 = await criar();
for (const p of [p1,p2]) await financeiro.req('POST',`/atividades/${p.id}/plano-financeiro`,{materiais:[{materialId:p.materiais[0].id,quantidadeCompra:0,origens:[{equipamentoId:unico.id,quantidade:1}]}]});
const respostas = await Promise.all([p1,p2].map(p=>financeiro.resposta('POST',`/atividades/${p.id}/aprovacao`,{})));
assert.deepEqual(respostas.map(r=>r.status).sort(),[200,409],'Só uma aprovação pode reservar a última unidade');
assert.equal((await consultar(unico.id)).quantidadeReservada,1);
const vencedor = respostas.find(r=>r.status===200).dados;
await financeiro.req('POST',`/atividades/${vencedor.id}/cancelamento`,{motivo:'Encerrar cenário de concorrência'});
assert.equal((await consultar(unico.id)).quantidadeReservada,0);
console.log('Concorrência real: duas aprovações sobre a última unidade, sem reserva excedente; cancelamento libera uma única vez.');

const pedirCompra = await criar();
await financeiro.req('POST',`/atividades/${pedirCompra.id}/plano-financeiro`,{materiais:[{materialId:pedirCompra.materiais[0].id,quantidadeCompra:1,justificativa:'Preservar a unidade existente na origem',origens:[]}]});
await financeiro.req('POST',`/atividades/${pedirCompra.id}/aprovacao`,{});
await estoque.req('POST',`/atividades/${pedirCompra.id}/materiais/${pedirCompra.materiais[0].id}/aquisicao`,{quantidade:1,numeroNota:'NF-AUDITORIA-OPS',identificacao:'OPS-COMPRA'});
const relatorio = await gerente.req('GET',`/relatorios/pedidos/${pedirCompra.id}`);
assert.ok(JSON.stringify(relatorio).includes('NF-AUDITORIA-OPS'));
const antesEdicao = JSON.stringify(relatorio);
await tecnico2.req('GET',`/relatorios/pedidos/${pedirCompra.id}`,undefined,403);
await tst.req('GET',`/relatorios/pedidos/${pedirCompra.id}`,undefined,403);
await rh.req('GET',`/relatorios/pedidos/${pedirCompra.id}`,undefined,[403,404]);
assert.equal(JSON.stringify(await gerente.req('GET',`/relatorios/pedidos/${pedirCompra.id}`)),antesEdicao);
const inventario = await gerente.req('GET',`/obras/${origem.id}/inventario-historico?data=${hoje()}`);
assert.ok(inventario);
console.log(`Auditoria de pedidos, nota fiscal, inventário histórico e permissões: OK. ${Object.values(clientes).reduce((n,c)=>n+c.verificacoes,0)} requisições verificadas.`);
